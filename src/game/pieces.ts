export function createSpawnPiece(type: PieceType): ActivePiece {
  return { type, rotation: 0, x: 3, y: 1 };
}

export function getPieceCells(piece: ActivePiece): Point[] {
  return PIECE_ROTATIONS[piece.type][piece.rotation].map((cell) => ({
    x: piece.x + cell.x,
    y: piece.y + cell.y,
  }));
}

