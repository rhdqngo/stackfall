export function getKickTests(type: PieceType, from: Rotation, to: Rotation): readonly Point[] {
  if (type === "O") return [{ x: 0, y: 0 }];
  const key = `${from}>${to}`;
  return (type === "I" ? I_KICKS[key] : JLSTZ_KICKS[key]) ?? [{ x: 0, y: 0 }];
}
